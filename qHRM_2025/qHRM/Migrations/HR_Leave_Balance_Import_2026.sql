-- ==============================================================================
-- Migration : Leave Booked & Balance Import (Leave Year 2026)
-- Source    : wwwroot/leave/Leave_booked_and_balance.xls
-- Scope     : ACTIVE employees only (HR_EmpGenInfo.Curr_Stat = 0)
--
--  1. Schema : HR_LvOpeningBalance gets BookedDays, SnapshotDate, SrcRef so an
--              imported "balance as at <date>" snapshot can be stored. The
--              LeaveBalanceService treats this snapshot as the base balance and
--              only deducts leaves created AFTER SnapshotDate.
--  2. Master : New leave type 'Absent' (LV_ABS, unpaid) + its policy row.
--  3. Data   : Upsert HR_LvOpeningBalance / HR_LvRunningBalance (override) and
--              log an 'Opening Balance (Import)' row in HR_LvBalanceTransaction.
--
--  Leave type mapping (Excel column -> HR_LvType.LvTyp_Code)
--    Paid           : Annual Leave - Based Joining Month -> LV_ANL
--                     Casual Leave                      -> LV_CSL
--                     Maternity Leave                   -> LV_MTN
--    Unpaid         : Absent                            -> LV_ABS  (new)
--                     Emergency Leave                   -> LV_EMG_UPD
--                     Hajj Leave                        -> LV_HAJ
--    Partially Paid : Sick Leave                        -> LV_SICK
--  Cells marked 'N/A' are not applicable and are skipped.
--  Running balance : EntitledDays = Booked + Balance, UsedDays = Booked,
--                    BalanceDays  = Balance (as given in the file)
--
--  Script is re-runnable (idempotent).
-- ==============================================================================
SET NOCOUNT ON;
GO

-- ------------------------------------------------------------------------------
-- 1. SCHEMA : snapshot columns on HR_LvOpeningBalance
-- ------------------------------------------------------------------------------
IF NOT EXISTS (SELECT 1 FROM sys.columns WHERE object_id = OBJECT_ID(N'[dbo].[HR_LvOpeningBalance]') AND name = 'BookedDays')
    ALTER TABLE [dbo].[HR_LvOpeningBalance] ADD [BookedDays] DECIMAL(5,2) NOT NULL
        CONSTRAINT [DF_HR_LvOpeningBalance_BookedDays] DEFAULT (0);

IF NOT EXISTS (SELECT 1 FROM sys.columns WHERE object_id = OBJECT_ID(N'[dbo].[HR_LvOpeningBalance]') AND name = 'SnapshotDate')
    ALTER TABLE [dbo].[HR_LvOpeningBalance] ADD [SnapshotDate] DATETIME NULL;

IF NOT EXISTS (SELECT 1 FROM sys.columns WHERE object_id = OBJECT_ID(N'[dbo].[HR_LvOpeningBalance]') AND name = 'SrcRef')
    ALTER TABLE [dbo].[HR_LvOpeningBalance] ADD [SrcRef] NVARCHAR(100) NULL;
GO

-- ------------------------------------------------------------------------------
-- 2. MASTER : 'Absent' leave type (unpaid) + policy
-- ------------------------------------------------------------------------------
IF NOT EXISTS (SELECT 1 FROM [dbo].[HR_LvType] WHERE [LvTyp_Code] = N'LV_ABS')
BEGIN
    DECLARE @NewLvTypId INT = (SELECT ISNULL(MAX([LvTyp_Id]), 0) + 1 FROM [dbo].[HR_LvType]);

    INSERT INTO [dbo].[HR_LvType]
        ([LvTyp_Id], [LvTyp_Code], [Name_Eng], [Name_Arb], [Desc], [Elg_Days], [Max_CntDays],
         [Aprl_Rqd], [Pre_Shld], [Slry_Dct_Fct], [Rjn_Fm_Rqd], [Ent_Id], [Rec_Stat], [Crt_DateTime], [Encsh])
    VALUES
        (@NewLvTypId, N'LV_ABS', N'Absent', NULL, N'Absent (Unpaid / No-Pay)', 0, 0,
         0, 0, 1.00, 0, 1, 1, GETDATE(), 0);
END

IF NOT EXISTS (SELECT 1 FROM [dbo].[HR_LvPolicy] p JOIN [dbo].[HR_LvType] t ON t.[LvTyp_Id] = p.[LvTyp_Id] WHERE t.[LvTyp_Code] = N'LV_ABS')
BEGIN
    INSERT INTO [dbo].[HR_LvPolicy]
        ([LvTyp_Id], [Desc], [App_After_Days], [Elg_Days], [Full_Paid_Days], [Half_Paid_Days], [No_Pay_Days],
         [Is_No_Pay], [Prd_Unit], [Ent_Id], [Rec_Stat], [Crt_DateTime], [Crt_By])
    SELECT [LvTyp_Id], N'Absent - unpaid, no entitlement', 0, 0, 0, 0, 0,
           1, N'YEAR', 1, 1, GETDATE(), N'Migration'
    FROM [dbo].[HR_LvType] WHERE [LvTyp_Code] = N'LV_ABS';
END
GO

