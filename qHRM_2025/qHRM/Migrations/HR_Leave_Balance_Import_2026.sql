UPDATE i SET i.LvTyp_Id = t.[LvTyp_Id]
FROM #LvImp i JOIN [dbo].[HR_LvType] t ON t.[LvTyp_Code] = i.LvTyp_Code;

BEGIN TRY
    BEGIN TRANSACTION;

    -- 3a. Opening balance snapshot (override)
    MERGE [dbo].[HR_LvOpeningBalance] AS tgt
    USING (SELECT * FROM #LvImp WHERE Curr_Stat = 0 AND LvTyp_Id IS NOT NULL) AS src
       ON tgt.[EmpSysId] = src.Emp_Sys_Id AND tgt.[LvTypId] = src.LvTyp_Id AND tgt.[LvYear] = @LvYear
    WHEN MATCHED THEN UPDATE SET
        [OpeningDays]  = src.Balance,
        [BookedDays]   = src.Booked,
        [SnapshotDate] = @SnapDt,
        [SrcRef]       = @SrcRef,
        [Remarks]      = N'Imported from ' + @SrcRef,
        [MdfId]        = @CrtId,
        [MdfDateTime]  = @SnapDt
    WHEN NOT MATCHED THEN INSERT
        ([EmpSysId], [LvTypId], [LvYear], [OpeningDays], [BookedDays], [SnapshotDate], [SrcRef], [Remarks], [CrtId], [CrtDateTime])
        VALUES (src.Emp_Sys_Id, src.LvTyp_Id, @LvYear, src.Balance, src.Booked, @SnapDt, @SrcRef,
                N'Imported from ' + @SrcRef, @CrtId, @SnapDt);

    -- 3b. Audit trail (captures the balance before override)
    INSERT INTO [dbo].[HR_LvBalanceTransaction]
        ([EmpSysId], [LvTypId], [LvYear], [TrnType], [LvId], [Days], [BalanceBefore], [BalanceAfter], [Remarks], [CrtId], [CrtDateTime])
    SELECT src.Emp_Sys_Id, src.LvTyp_Id, @LvYear, N'Opening Balance (Import)', NULL,
           src.Balance, ISNULL(rb.[BalanceDays], 0), src.Balance,
           N'Imported from ' + @SrcRef + N' | Booked: ' + CAST(src.Booked AS NVARCHAR(10)) + N', Balance: ' + CAST(src.Balance AS NVARCHAR(10)),
           @CrtId, @SnapDt
    FROM #LvImp src
    LEFT JOIN [dbo].[HR_LvRunningBalance] rb
           ON rb.[EmpSysId] = src.Emp_Sys_Id AND rb.[LvTypId] = src.LvTyp_Id AND rb.[LvYear] = @LvYear
    WHERE src.Curr_Stat = 0 AND src.LvTyp_Id IS NOT NULL;

    -- 3c. Running balance (override)
    MERGE [dbo].[HR_LvRunningBalance] AS tgt
    USING (SELECT * FROM #LvImp WHERE Curr_Stat = 0 AND LvTyp_Id IS NOT NULL) AS src
       ON tgt.[EmpSysId] = src.Emp_Sys_Id AND tgt.[LvTypId] = src.LvTyp_Id AND tgt.[LvYear] = @LvYear
    WHEN MATCHED THEN UPDATE SET
        [EntitledDays] = src.Booked + src.Balance,
        [UsedDays]     = src.Booked,
        [BalanceDays]  = src.Balance,
        [LastUpdated]  = @SnapDt
    WHEN NOT MATCHED THEN INSERT
        ([EmpSysId], [LvTypId], [LvYear], [EntitledDays], [UsedDays], [BalanceDays], [LastUpdated])
        VALUES (src.Emp_Sys_Id, src.LvTyp_Id, @LvYear, src.Booked + src.Balance, src.Booked, src.Balance, @SnapDt);

    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;

